/** Impostazioni salvate sul telefono: lingua e accettazione dei termini d'uso. */
object Settings {
    /** Aumentalo quando cambiano i termini: gli utenti dovranno accettarli di nuovo. */
    const val TERMS_VERSION = 1

    private fun sp(c: Context) = c.getSharedPreferences("settings", Context.MODE_PRIVATE)
    fun lang(c: Context): String? = sp(c).getString("lang", null)
    fun setLang(c: Context, l: String) { sp(c).edit().putString("lang", l).apply() }
    fun termsAccepted(c: Context): Boolean = sp(c).getInt("terms_version", 0) >= TERMS_VERSION
    fun acceptTerms(c: Context) { sp(c).edit().putInt("terms_version", TERMS_VERSION).apply() }
}

